#!/usr/bin/env python3
"""Write the two generated Lean files from the spec constants and the ephemeris.

`lean/MarsCheck/Spec.lean`       numbers read from ethereum/consensus-specs, each with its source line
`lean/MarsCheck/Ephemeris.lean`  Mars one-way light time per day, in milliseconds, from NASA/JPL Horizons

Nothing in these files is typed in by hand, so the theorems are about the same inputs the Python
model uses.
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = json.loads((ROOT / "data" / "spec_constants.json").read_text())
v = spec["values"]

NAMES = {
    "slotDurationMs": "SLOT_DURATION_MS",
    "attestationDueBps": "ATTESTATION_DUE_BPS",
    "slotsPerEpoch": "SLOTS_PER_EPOCH",
    "minAttestationInclusionDelay": "MIN_ATTESTATION_INCLUSION_DELAY",
    "timelySourceWeight": "TIMELY_SOURCE_WEIGHT",
    "timelyTargetWeight": "TIMELY_TARGET_WEIGHT",
    "timelyHeadWeight": "TIMELY_HEAD_WEIGHT",
}
out = ["/-! Generated by tools/gen_lean.py from data/spec_constants.json. Do not edit.",
       f"consensus-specs commit {spec['consensus_specs_commit']} -/", "",
       "namespace MarsCheck", ""]
for lean, key in NAMES.items():
    out.append(f"/-- `{key}`, `{v[key]['source']}` -/")
    out.append(f"def {lean} : Nat := {v[key]['value']}")
    out.append("")
out += ["end MarsCheck", ""]
(ROOT / "lean" / "MarsCheck" / "Spec.lean").write_text("\n".join(out))

rows = list(csv.DictReader(open(ROOT / "results" / "daily.csv")))
# One-way light time in milliseconds. Horizons gives range in AU; the Python side rounds to 0.1 s.
ms = [round(float(r["one_way_s"]) * 10) * 100 for r in rows]
lines = ["/-! Generated by tools/gen_lean.py from results/daily.csv (NASA/JPL Horizons, Mars seen from",
         f"Earth's center, {rows[0]['date']} to {rows[-1]['date']}, {len(rows)} days). Do not edit. -/", "",
         "namespace MarsCheck", "",
         "/-- One-way light time Earth to Mars, in milliseconds, one entry per day. -/",
         "def oneWayMs : List Nat :="]
for k in range(0, len(ms), 12):
    chunk = ", ".join(str(x) for x in ms[k:k + 12])
    lines.append(("  [" if k == 0 else "  ") + chunk + ("," if k + 12 < len(ms) else "]"))
lines += ["", "end MarsCheck", ""]
(ROOT / "lean" / "MarsCheck" / "Ephemeris.lean").write_text("\n".join(lines))
print("wrote Spec.lean and Ephemeris.lean;", len(ms), "days")
